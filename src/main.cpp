// ================= Serial Command =================
void handleSerialCommand() {
  if (!Serial.available()) return;

  String cmd = Serial.readStringUntil('\n');
  cmd.trim();
  cmd.toUpperCase();

  if (cmd == "RESETWIFI") {
    Serial.println(">> Reset WiFi settings...");
    WiFiManager wm;
    wm.resetSettings();
    delay(500);
    ESP.restart();
  }
  else if (cmd == "REBOOT") {
    Serial.println(">> Reboot...");
    ESP.restart();
  }
  else if (cmd.startsWith("DEVICE_ID=")) {
    String newId = cmd.substring(10);
    newId.trim();
    if (newId.length() > 0) {
      prefs.putString("device_id", newId);
      device_id = newId;
      Serial.print(">> Device ID disimpan: ");
      Serial.println(device_id);
    }
  }
  else if (cmd == "STATUS") {
    Serial.printf(">> device_id=%s  WiFi=%d  HTTP=%d\n",
                  device_id.c_str(), WiFi.status(), lastHttpCode);
  }
  else {
    Serial.println(">> Perintah: RESETWIFI | REBOOT | STATUS | DEVICE_ID=xxx");
  }
}

// ================= Tombol Reset WiFi =================
void checkResetButton() {
  static unsigned long pressStart = 0;

  if (digitalRead(RESET_BUTTON_PIN) == LOW) {
    if (pressStart == 0) pressStart = millis();
    if (millis() - pressStart > 3000) {
      Serial.println(">> Tombol ditekan 3 detik, reset WiFi...");
      display.clearDisplay();
      display.setCursor(0, 0);
      display.println("Reset WiFi...");
      display.display();

      WiFiManager wm;
      wm.resetSettings();
      delay(500);
      ESP.restart();
    }
  } else {
    pressStart = 0;
  }
}

// ================= Kirim ke API =================
int sendData(float temperature, unsigned long uptime) {
  if (WiFi.status() != WL_CONNECTED) {
    Serial.println("WiFi terputus, kirim dibatalkan");
    return -1;
  }

  // Kirim sebagai query parameter (tetap method POST, body kosong)
  String url = String(apiEndpoint)
             + (String(apiEndpoint).indexOf('?') >= 0 ? "&" : "?")
             + "temp=" + String(temperature, 2)
             + "&id_devices=" + String(device_id)
             + "&unit=" + String(unit)
             + "&uptime=" + String(uptime)
             + "&status=Online";

  HTTPClient http;
  http.begin(url);
  http.setTimeout(5000);

  Serial.println("POST url:");
  Serial.println(url);

  int code = http.POST("");

  // Hanya tampilkan kode status, bukan raw body
  if (code > 0) {
    Serial.printf("API status code: %d\n", code);
  } else {
    Serial.printf("API error: %s\n", http.errorToString(code).c_str());
  }

  http.end();
  return code;
}

// ================= Setup =================
void setup() {
  Serial.begin(115200);
  delay(200);

  pinMode(RESET_BUTTON_PIN, INPUT_PULLUP);

  sensors.begin();
  Wire.begin(21, 22);

  if (!display.begin(SSD1306_SWITCHCAPVCC, OLED_ADDR)) {
    Serial.println("OLED gagal diinisialisasi");
    while (true) delay(100);
  }
  showBootScreen();

  // Load device_id dari NVS; kalau belum di-set, turunkan dari MAC unik ESP32
  prefs.begin("iot", false);
  char macBuf[20];
  snprintf(macBuf, sizeof(macBuf), "esp32-%04X%08X",
           (uint16_t)(ESP.getEfuseMac() >> 32), (uint32_t)ESP.getEfuseMac());
  device_id = prefs.getString("device_id", macBuf);
  Serial.print("Device ID: ");
  Serial.println(device_id);

  // ---- WiFiManager (ganti WiFi tanpa upload ulang) ----
  WiFiManager wm;
  wm.setConfigPortalTimeout(180);       // timeout portal 3 menit
  wm.setAPCallback(showWifiSetupScreen);
  // wm.resetSettings();                 // uncomment untuk uji coba

  // ---- WiFi: deteksi Wokwi vs hardware asli ----
  Serial.println("Scanning WiFi...");
  int n = WiFi.scanNetworks();

  bool isWokwi = false;
  for (int i = 0; i < n; i++) {
    if (WiFi.SSID(i) == "Wokwi-GUEST") {
      isWokwi = true;
      break;
    }
  }

  if (isWokwi) {
    // === MODE SIMULASI WOKWI ===
    Serial.println("Wokwi terdeteksi → connect ke Wokwi-GUEST");
    WiFi.begin("Wokwi-GUEST", "", 6);  // channel 6 biar cepat

    unsigned long start = millis();
    while (WiFi.status() != WL_CONNECTED && millis() - start < 10000) {
      delay(200);
      Serial.print(".");
    }
  } else {
    // === MODE HARDWARE ASLI ===
    Serial.println("Hardware asli → pakai WiFiManager");
    WiFiManager wm;
    wm.setConfigPortalTimeout(180);
    wm.setAPCallback(showWifiSetupScreen);

    if (!wm.autoConnect(AP_NAME, AP_PASSWORD)) {
      Serial.println("WiFi gagal, restart...");
      ESP.restart();
    }
  }

  Serial.println("\nWiFi terhubung!");
  Serial.print("SSID: ");
  Serial.println(WiFi.SSID());
  Serial.print("IP  : ");
  Serial.println(WiFi.localIP());
}

unsigned long lastRead = 0;
const unsigned long READ_INTERVAL = 1000;  // baca + update OLED tiap 1 detik

void loop() {
  handleSerialCommand();
  checkResetButton();          // ← dicek terus, cepat

  // Baca sensor tiap detik (baca terus-menerus), kirim ke API tetap berkala (sendInterval)
  if (millis() - lastRead >= READ_INTERVAL) {
    lastRead = millis();

    // ponytail: requestTemperatures() blocking ~750ms. Kalau perlu baca lebih rapat,
    // pakai sensors.setWaitForConversion(false) + baca hasil di iterasi berikutnya.
    sensors.requestTemperatures();
    float tempC = sensors.getTempCByIndex(0);
    unsigned long uptime = millis() / 1000;

    if (tempC == DEVICE_DISCONNECTED_C) {
      Serial.println("Sensor DS18B20 tidak terbaca");
      display.clearDisplay();
      display.setCursor(0, 0);
      display.println("Sensor error");
      display.display();
    } else {
      // Kirim ke API berkala, terpisah dari irama baca sensor
      if (millis() - lastSend >= sendInterval) {
        lastSend = millis();
        lastHttpCode = sendData(tempC, uptime);
        hasSentOnce = true;
      }

      showMainScreen(tempC, uptime);

      Serial.printf("Temp: %.2f %s | Uptime: %lu s | HTTP: %d\n",
                    tempC, unit, uptime, lastHttpCode);
    }
  }
}